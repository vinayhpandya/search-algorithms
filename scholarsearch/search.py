"""Search PR5's OpenSearch index by BM25, SPECTER2 HNSW, or RRF hybrid.

The query JSON is produced by `python -m scholarsearch.query_embed` using the
separate Transformers-4 embedding environment; this module needs no adapters.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from .config import setting
from .query_embed import QUERY_ADAPTER
from .embeddings import MODEL
from .vector_index import validate_endpoint

EXCLUDE = ['embedding']


def load_query_vector(path: str, expected_query: str) -> list[float]:
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    if (data.get('query') != expected_query.strip() or data.get('model') != MODEL
            or data.get('adapter') != QUERY_ADAPTER or data.get('dimension') != 768
            or data.get('normalized') is not True):
        raise ValueError('Query vector metadata does not match the requested query/model/adapter')
    vector = np.asarray(data.get('vector'), dtype=np.float32)
    if vector.shape != (768,) or not np.isfinite(vector).all():
        raise ValueError('Query vector must contain 768 finite values')
    if not np.isclose(np.linalg.norm(vector), 1, atol=1e-3):
        raise ValueError('Query vector must be normalized')
    return vector.tolist()


def bm25_body(query: str, size: int) -> dict:
    return {'size': size, '_source': {'excludes': EXCLUDE}, 'query': {
        'multi_match': {'query': query, 'fields': ['title^3', 'abstract'], 'type': 'best_fields'}}}


def dense_body(vector: list[float], size: int) -> dict:
    return {'size': size, '_source': {'excludes': EXCLUDE}, 'query': {
        'knn': {'embedding': {'vector': vector, 'k': size}}}}


def extract_hits(response: dict) -> list[dict]:
    results = []
    for hit in response['hits']['hits']:
        results.append({'id': str(hit['_id']), 'score': float(hit['_score']),
                        **{k: v for k, v in hit.get('_source', {}).items() if k != 'embedding'}})
    return results


def rrf(rankings: list[list[dict]], *, k: int = 60, limit: int = 10) -> list[dict]:
    if k < 1 or limit < 1:
        raise ValueError('k and limit must be positive')
    combined: dict[str, dict] = {}
    for source_index, ranking in enumerate(rankings):
        seen = set()
        for rank, hit in enumerate(ranking, 1):
            paper_id = hit['id']
            if paper_id in seen:
                continue
            seen.add(paper_id)
            if paper_id not in combined:
                combined[paper_id] = {**hit, 'score': 0., 'bm25_rank': None, 'dense_rank': None}
            combined[paper_id]['score'] += 1 / (k + rank)
            label = 'bm25_rank' if source_index == 0 else 'dense_rank'
            combined[paper_id][label] = rank
    return sorted(combined.values(), key=lambda hit: (-hit['score'], hit['id']))[:limit]


def search(*, text: str, mode: str, url: str, index: str, limit: int = 10,
           candidate_k: int = 50, query_vector: list[float] | None = None, client=None) -> list[dict]:
    if mode not in {'bm25', 'dense', 'hybrid'}:
        raise ValueError('mode must be bm25, dense or hybrid')
    if not text.strip() or limit < 1 or candidate_k < limit:
        raise ValueError('Query must be nonempty and candidate_k must be >= limit >= 1')
    validate_endpoint(url)
    if mode != 'bm25':
        if query_vector is None or len(query_vector) != 768:
            raise ValueError('dense/hybrid search requires a 768-dimensional query vector')
    if client is None:
        from opensearchpy import OpenSearch
        client = OpenSearch(hosts=[url], timeout=30, max_retries=3, retry_on_timeout=True)
    if mode == 'bm25':
        return extract_hits(client.search(index=index, body=bm25_body(text, limit)))
    if mode == 'dense':
        return extract_hits(client.search(index=index, body=dense_body(query_vector, limit)))
    lexical = extract_hits(client.search(index=index, body=bm25_body(text, candidate_k)))
    semantic = extract_hits(client.search(index=index, body=dense_body(query_vector, candidate_k)))
    return rrf([lexical, semantic], limit=limit)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--query', required=True, help='User search query')
    p.add_argument('--mode', choices=['bm25', 'dense', 'hybrid'], default='hybrid')
    p.add_argument('--query-vector-file', help='Generated by scholarsearch.query_embed; required for dense/hybrid')
    p.add_argument('--opensearch-url', default=None)
    p.add_argument('--index', default=None)
    p.add_argument('--limit', type=int, default=10)
    p.add_argument('--candidate-k', type=int, default=50)
    args = p.parse_args()
    vector = None
    if args.mode != 'bm25':
        if not args.query_vector_file:
            p.error('--query-vector-file is required for dense/hybrid mode')
        vector = load_query_vector(args.query_vector_file, args.query)
    print(json.dumps(search(text=args.query, mode=args.mode,
                            url=args.opensearch_url or setting('OPENSEARCH_URL', 'http://localhost:9200'),
                            index=args.index or setting('OPENSEARCH_HYBRID_INDEX', 'scholarsearch-malware-hnsw-v1'),
                            limit=args.limit, candidate_k=args.candidate_k,
                            query_vector=vector), indent=2))


if __name__ == '__main__':
    main()
